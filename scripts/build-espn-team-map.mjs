// One-off generator for src/data/espnTeamMap.json -- maps our team ids (slugify(name), same
// convention as fetch-cfb-data.mjs) to ESPN's own numeric team id, so the client-side live-score
// fetch (src/utils/useLiveScores.js) can join an ESPN scoreboard event back to one of our games
// without ever seeing a CFBD id (ESPN's API knows nothing about CFBD).
//
// ESPN's public teams endpoint ignores the `groups` filter (confirmed live: groups=80 returns the
// exact same list as no filter at all, ~760 teams across every division from FBS down to D3), so
// this fetches everything and matches by exact slug instead of trying to pre-filter to FBS.
//
// Run with: node scripts/build-espn-team-map.mjs
// Re-run only when a tracked team renames or a new one needs mapping (realignment, promotion to
// FBS, etc.) -- MANUAL_OVERRIDES below covers every case the automatic pass can't resolve on its
// own (an ESPN `location` string that doesn't slugify to the same thing we use).

import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

// Byte-identical to fetch-cfb-data.mjs's slugify() -- MUST stay in sync, since our team ids (the
// keys we're mapping TO) are generated by that exact function; a divergence here would silently
// produce ids that never match anything in data/current.json.
function slugify(name) {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

// Confirmed live cases where ESPN's `location` string doesn't slugify to our id, even though it's
// unambiguously the same school -- each comment is why. Keyed by OUR id, value is the exact ESPN
// team `id` to use (not a location string -- some of these are disambiguating between two ESPN
// teams that legitimately share the same `location`).
const MANUAL_OVERRIDES = {
  // ESPN's `location` for both is exactly "Charlotte" -- 2429 is the FBS 49ers (Conference USA);
  // 3253 ("Charlotte Saints") is an unrelated small program. Confirmed via ESPN's own team pages.
  charlotte: '2429',
  // Same collision -- 2653 is the FBS Troy Trojans (Sun Belt, Troy, AL); 3237 ("Troy Vikings") is
  // a different, non-FBS Troy program. Confirmed via ESPN's own team pages.
  troy: '2653',
};

async function main() {
  const currentPath = join(ROOT, 'data', 'current.json');
  const { default: raw } = await import(pathToFileURL(currentPath).href, { with: { type: 'json' } });
  const ourTeams = Object.entries(raw.teams).map(([id, t]) => [id, t.name]);

  const res = await fetch(
    'https://site.api.espn.com/apis/site/v2/sports/football/college-football/teams?limit=1500',
  );
  if (!res.ok) throw new Error(`ESPN teams fetch failed: HTTP ${res.status}`);
  const body = await res.json();
  const espnTeams = body.sports[0].leagues[0].teams.map((t) => t.team);

  // slug(location) -> [espnTeam, ...] -- collect ALL teams per slug so a collision (two different
  // schools slugifying to the same string) is visible instead of silently picking one.
  const bySlug = new Map();
  for (const t of espnTeams) {
    const slug = slugify(t.location);
    if (!bySlug.has(slug)) bySlug.set(slug, []);
    bySlug.get(slug).push(t);
  }

  const map = {};
  const unmatched = [];
  const ambiguous = [];

  for (const [id, name] of ourTeams) {
    if (MANUAL_OVERRIDES[id]) {
      map[id] = MANUAL_OVERRIDES[id];
      continue;
    }
    const candidates = bySlug.get(id) ?? [];
    if (candidates.length === 1) {
      map[id] = candidates[0].id;
    } else if (candidates.length > 1) {
      ambiguous.push({ id, name, candidates: candidates.map((c) => ({ espnId: c.id, location: c.location, displayName: c.displayName })) });
    } else {
      // No exact slug match -- surface any ESPN team whose location shares a word with our name,
      // as a hint for manual review (NOT auto-applied -- these are guesses, not matches).
      const nameWords = new Set(slugify(name).split('-'));
      const hints = espnTeams
        .filter((t) => slugify(t.location).split('-').some((w) => nameWords.has(w)))
        .map((t) => ({ espnId: t.id, location: t.location, displayName: t.displayName }));
      unmatched.push({ id, name, hints });
    }
  }

  const outPath = join(ROOT, 'src', 'data', 'espnTeamMap.json');
  writeFileSync(outPath, JSON.stringify(map, null, 2) + '\n');
  console.log(`Wrote ${Object.keys(map).length}/${ourTeams.length} matches to ${outPath}`);

  if (ambiguous.length) {
    console.log(`\n${ambiguous.length} AMBIGUOUS (multiple ESPN teams share the slug -- needs a MANUAL_OVERRIDES entry or code fix):`);
    console.log(JSON.stringify(ambiguous, null, 2));
  }
  if (unmatched.length) {
    console.log(`\n${unmatched.length} UNMATCHED (no exact slug match -- review hints and add to MANUAL_OVERRIDES):`);
    console.log(JSON.stringify(unmatched, null, 2));
  }
  if (!ambiguous.length && !unmatched.length) {
    console.log('All teams matched cleanly.');
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
